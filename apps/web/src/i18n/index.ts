const catalogs: Record<Locale, Record<MessageKey, string>> = { en, id, su };

/* ------------------------------------------------------------------ */
/* Locale resolution — mirrors the boot script in index.html.         */
/* ------------------------------------------------------------------ */

function detectLocale(): Locale {
  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (isLocale(stored)) return stored;
  } catch {
    // localStorage throws in Safari private mode; fall through to the navigator scan.
  }
  const languages: readonly string[] = typeof navigator === 'undefined' ? [] : navigator.languages ?? [navigator.language];
  for (const entry of languages) {
    const base = entry?.split('-')[0];
    if (isLocale(base)) return base;
  }
  return 'en';
}

/** Replace `{name}` placeholders; unknown placeholders are left untouched. */
function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

export function translate(locale: Locale, key: MessageKey, params?: Record<string, string | number>): string {
  return interpolate(catalogs[locale][key] ?? catalogs.en[key], params);
}

/* ------------------------------------------------------------------ */
/* Provider                                                            */
/* ------------------------------------------------------------------ */

interface LanguageContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, params?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale);

  // The boot script already set `lang` before React mounted; this keeps them in step afterwards.
  useEffect(() => { document.documentElement.lang = locale; }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, next);
    } catch {
      // Persisting is best-effort; the in-memory choice still applies for this session.
    }
  }, []);

  const t = useCallback((key: MessageKey, params?: Record<string, string | number>) => translate(locale, key, params), [locale]);
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  // createElement keeps this module a `.ts` file (the index.html boot comment names this path).
  return createElement(LanguageContext.Provider, { value }, children);
}

export function useTranslation(): LanguageContextValue {
  const value = useContext(LanguageContext);
  if (!value) throw new Error('useTranslation must be used inside a LanguageProvider.');
  return value;
}
